// Dependência opcional de validação; não faz parte do bundle mobile.
const { PGlite } = await import(process.env.PGLITE_MODULE ?? '@electric-sql/pglite');
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`
 create role authenticated;
 create table households(id uuid primary key);
 insert into households values ('00000000-0000-0000-0000-000000000001'), ('00000000-0000-0000-0000-000000000002');
 create function auth_household_id() returns uuid language sql stable as $$
 select coalesce(nullif(current_setting('test.household', true), ''), '00000000-0000-0000-0000-000000000001')::uuid $$;
`);
await db.exec(readFileSync(new URL('../supabase/migrations/0009_investments.sql', import.meta.url), 'utf8'));
await db.exec(readFileSync(new URL('../supabase/migrations/0010_investment_maturity.sql', import.meta.url), 'utf8'));
await db.exec(`grant usage on schema public to authenticated; grant select, insert, update, delete on all tables in schema public to authenticated; set role authenticated;`);
const bank = (await db.query('select id from investment_institutions limit 1')).rows[0].id;
const create = async (category, type, amount, quantity) => (await db.query(`select create_investment('Teste', 'metas', $1, $2, $3, $4, $5, current_date) as id`, [category, type, bank, amount, quantity])).rows[0].id;
const pos = async id => (await db.query('select * from investments where id=$1',[id])).rows[0];
const totalPositions = async () => (await db.query('select count(*) as n from investments')).rows[0].n;
const id = await create('variavel', 'Ação', 2000, 100);
assert.equal(Number((await pos(id)).current_value), 2000);
assert.equal((await pos(id)).valued_at, null);
await db.query("update investments set current_value=2500, valued_at='2026-11-04T10:00:00Z' where id=$1",[id]);
await db.query('insert into investment_contributions(investment_id, amount, quantity, occurred_on) values ($1,1500,50,current_date)',[id]);
assert.equal(Number((await pos(id)).current_value), 4000);
assert.ok((await pos(id)).valued_at);
const sums = (await db.query('select sum(amount) as amount, sum(quantity) as quantity from investment_contributions where investment_id=$1',[id])).rows[0];
assert.equal(Number(sums.amount),3500); assert.equal(Number(sums.quantity),150);
const second = (await db.query('select id from investment_contributions where investment_id=$1 and amount=1500',[id])).rows[0].id;
await db.query('update investment_contributions set amount=1000, quantity=40 where id=$1',[second]);
assert.equal(Number((await pos(id)).current_value),3500);
await db.query('delete from investment_contributions where id=$1',[second]);
assert.equal(Number((await pos(id)).current_value),2500);
const before = await totalPositions();
await assert.rejects(create('variavel','Ação',100,null),/Quantidade obrigatória/);
assert.equal(await totalPositions(),before, 'cadastro deve ser desfeito se aporte inicial falhar');
await assert.rejects(create('fixa','Ação',0,null));
await assert.rejects(create('fixa','CDB',10,1),/Quantidade obrigatória/);
await assert.rejects(create('variavel','Ação',0,1));
const empty = await create('variavel','FII',0,null);
assert.equal(Number((await pos(empty)).current_value),0);
assert.equal((await db.query('select count(*) as n from investment_contributions where investment_id=$1',[empty])).rows[0].n,0);
const fixed = await create('fixa','CDB',1000,null);
await assert.rejects(db.query('insert into investment_contributions(investment_id, amount, quantity, occurred_on) values ($1,-1,null,current_date)',[fixed]));
await assert.rejects(db.query("insert into investment_contributions(investment_id, amount, quantity, occurred_on) values ($1,10,null,current_date+1)",[fixed]));
assert.equal(Number((await pos(fixed)).current_value),1000,'falha no aporte não deve alterar o saldo');
await db.query('update investments set current_value=0 where id=$1',[fixed]);
await db.query('delete from investment_contributions where investment_id=$1',[fixed]);
assert.equal(Number((await pos(fixed)).current_value),0);
await db.exec("set test.household='00000000-0000-0000-0000-000000000002'");
assert.equal(await totalPositions(),0,'RLS deve esconder posições de outra casa');
await assert.rejects(db.query('insert into investment_contributions(investment_id, amount, quantity, occurred_on) values ($1,100,10,current_date)',[id]));
await db.query('update investments set current_value=1 where id=$1',[id]);
await db.exec("set test.household='00000000-0000-0000-0000-000000000001'");
assert.equal(Number((await pos(id)).current_value),2500,'outra casa não pode editar posição');
await db.query('delete from investments where id=$1',[id]);
assert.equal((await db.query('select count(*) as n from investment_contributions where investment_id=$1',[id])).rows[0].n,0);
// Nova assinatura mantém a criação atômica e a antiga continua compatível.
const maturing = async (category, type, maturity) => (await db.query(
  `select create_investment('Vencimento', 'apartamento', $1, $2, $3, 100, $4, current_date, $5::date) as id`,
  [category, type, bank, category === 'variavel' ? 10 : null, maturity])).rows[0].id;
const withDate = await maturing('fixa', 'CDB', '2028-05-20');
assert.equal(new Date((await pos(withDate)).maturity_date).toISOString().slice(0, 10), '2028-05-20');
assert.equal(Number((await pos(withDate)).current_value), 100);
const withoutDate = await maturing('fixa', 'CDB', null);
assert.equal((await pos(withoutDate)).maturity_date, null);
const oldClient = await create('fixa', 'LCI', 0, null);
assert.equal((await pos(oldClient)).maturity_date, null, 'assinatura antiga continua funcional');
await db.query("update investments set maturity_date='2029-06-10' where id=$1", [withoutDate]);
assert.equal(new Date((await pos(withoutDate)).maturity_date).toISOString().slice(0, 10), '2029-06-10');
await db.query('update investments set maturity_date=null where id=$1', [withoutDate]);
assert.equal((await pos(withoutDate)).maturity_date, null);
const beforeInvalid = await totalPositions();
await assert.rejects(maturing('variavel', 'Ação', '2028-05-20'), /investments_maturity_fixed_only/);
assert.equal(await totalPositions(), beforeInvalid, 'vencimento inválido desfaz posição e aporte');
const variable = await maturing('variavel', 'Ação', null);
await assert.rejects(db.query("update investments set maturity_date='2028-05-20' where id=$1", [variable]));
await assert.rejects(db.query("update investments set maturity_date='infinity' where id=$1", [withDate]));
console.log('PostgreSQL: vencimento opcional, assinatura antiga, edição, validação por categoria e atomicidade passaram.');
console.log('PostgreSQL: migração, cadastro atômico, aportes, edição/exclusão, avaliação manual, validações e RLS passaram.');
await db.close();
